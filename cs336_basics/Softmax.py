import torch


def softmax(x: torch.Tensor, dim: int) -> torch.Tensor:
    """
    Apply softmax to the specified dimension of the input tensor.

    Args:
        x: Input tensor of arbitrary shape
        dim: Dimension to apply softmax over

    Returns:
        Tensor of same shape with softmax applied to specified dimension
    """
    # x.shape: (..., d_dim, ...) - 任意形状的输入张量
    # 例如: (batch_size, seq_len, features) 或 (2, 3, 5)
    # 
    # 具体示例: x.shape = (2, 3, 5), dim=-1
    # x = [[[1, 2, 3, 4, 5],      # batch 0, row 0
    #       [6, 7, 8, 9, 10],     # batch 0, row 1
    #       [11, 12, 13, 14, 15]],# batch 0, row 2
    #      [[16, 17, 18, 19, 20], # batch 1, row 0
    #       [21, 22, 23, 24, 25], # batch 1, row 1
    #       [26, 27, 28, 29, 30]]]# batch 1, row 2
    
    # 步骤1: 数值稳定性 - 减去最大值
    # keepdim=True 保持维度，使得广播能正确工作
    max_value = x.max(dim=dim, keepdim=True).values
    # max_value.shape: (..., 1, ...) - 在 dim 维度上变为 1，其他维度保持不变
    # 例如: dim=-1 时，(2, 3, 5) -> (2, 3, 1)
    # 
    # 示例 (dim=-1, 沿最后一维取最大值):
    # max_value = [[[5],   # max(1,2,3,4,5) = 5
    #               [10],  # max(6,7,8,9,10) = 10
    #               [15]], # max(11,12,13,14,15) = 15
    #              [[20],  # max(16,17,18,19,20) = 20
    #               [25],  # max(21,22,23,24,25) = 25
    #               [30]]] # max(26,27,28,29,30) = 30
    # shape: (2, 3, 1) - 每一行（5个元素）的最大值
    
    x_shifted = x - max_value
    # x_shifted.shape: (..., d_dim, ...) - 与 x 相同的形状
    # 广播: (2, 3, 5) - (2, 3, 1) = (2, 3, 5)
    # 
    # 示例 (dim=-1):
    # x_shifted = [[[1-5, 2-5, 3-5, 4-5, 5-5],     = [[[-4, -3, -2, -1, 0],
    #               [6-10, 7-10, 8-10, 9-10, 10-10],  [-4, -3, -2, -1, 0],
    #               [11-15, 12-15, 13-15, 14-15, 15-15]], [-4, -3, -2, -1, 0]],
    #              [[16-20, 17-20, 18-20, 19-20, 20-20], [[-4, -3, -2, -1, 0],
    #               [21-25, 22-25, 23-25, 24-25, 25-25],  [-4, -3, -2, -1, 0],
    #               [26-30, 27-30, 28-30, 29-30, 30-30]]] [-4, -3, -2, -1, 0]]]
    # 每一行都减去了该行的最大值，确保数值稳定
    
    # 步骤2: 计算 exp
    exp_x = torch.exp(x_shifted)
    # exp_x.shape: (..., d_dim, ...) - 与 x 相同的形状
    # torch.exp() 是 element-wise 操作，对张量中的【每一个元素】都应用 exp
    # 不管 dim 是什么，这里对所有元素都做 exp(x_i)
    # 
    # 示例:
    # exp_x = [[[e^-4, e^-3, e^-2, e^-1, e^0],    ≈ [[[0.018, 0.050, 0.135, 0.368, 1.0],
    #           [e^-4, e^-3, e^-2, e^-1, e^0],        [0.018, 0.050, 0.135, 0.368, 1.0],
    #           [e^-4, e^-3, e^-2, e^-1, e^0]],       [0.018, 0.050, 0.135, 0.368, 1.0]],
    #          [[e^-4, e^-3, e^-2, e^-1, e^0],       [[0.018, 0.050, 0.135, 0.368, 1.0],
    #           [e^-4, e^-3, e^-2, e^-1, e^0],        [0.018, 0.050, 0.135, 0.368, 1.0],
    #           [e^-4, e^-3, e^-2, e^-1, e^0]]]       [0.018, 0.050, 0.135, 0.368, 1.0]]]
    
    # 步骤3: 归一化 - 除以和
    # keepdim=True 确保可以正确广播
    sum_exp = exp_x.sum(dim=dim, keepdim=True)
    # sum_exp.shape: (..., 1, ...) - 在 dim 维度上求和并保持维度为 1
    # 例如: dim=-1 时，(2, 3, 5) -> (2, 3, 1)
    # 
    # 示例 (dim=-1, 沿最后一维求和):
    # sum_exp = [[[0.018+0.050+0.135+0.368+1.0],  = [[[1.571],
    #             [1.571],                             [1.571],
    #             [1.571]],                            [1.571]],
    #            [[1.571],                            [[1.571],
    #             [1.571],                             [1.571],
    #             [1.571]]]                            [1.571]]]
    # shape: (2, 3, 1) - 每一行的 exp 值之和
    
    return exp_x / sum_exp
    # 输出.shape: (..., d_dim, ...) - 与输入 x 完全相同的形状
    # 广播: (2, 3, 5) / (2, 3, 1) = (2, 3, 5)
    # 
    # 示例 (dim=-1):
    # output = [[[0.018/1.571, 0.050/1.571, 0.135/1.571, 0.368/1.571, 1.0/1.571],
    #            [0.011, 0.032, 0.086, 0.234, 0.637],  # 每行和为 1.0
    #            [0.011, 0.032, 0.086, 0.234, 0.637]],
    #           [[0.011, 0.032, 0.086, 0.234, 0.637],
    #            [0.011, 0.032, 0.086, 0.234, 0.637],
    #            [0.011, 0.032, 0.086, 0.234, 0.637]]]
    # 最终结果：每一行（5个元素）是一个概率分布，和为 1.0
